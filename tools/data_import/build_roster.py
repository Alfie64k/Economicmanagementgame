def rec(r):
    (i,n,cur,reg,arch,gov,fx,bloc,lat,lon,pop,gdp,usd,sec,dem,fis,mac,dm,en,pol)=r
    inv,g,x,m=dem
    cons=round(1-inv-g-x+m,4)
    return {
     "id":i,"name":n,"currency":cur,"region":reg,"archetype":arch,"gov":gov,"fx":fx,"bloc":bloc,
     "lat":lat,"lon":lon,"popM":pop,"gdpLcuBn":gdp,"usdFx":usd,
     "sectors":dict(zip(["agri","energy","manuf","services","finance","public"],sec)),
     "demand":{"cons":cons,"inv":inv,"gov":g,"exp":x,"imp":m},
     "fiscal":dict(zip(["revenue","health","education","defence","infra","rnd","deficit","debt","resourceRevenue","foreignDebtShare"],fis)),
     "macro":dict(zip(["policyRate","yield10","inflation","unemployment","gini","growthTrend","currentAccount","inflationTarget","cbIndependence"],mac)),
     "demog":dict(zip(["young","old","fertility","lifeExp","participation","migration"],dm)),
     "energy":dict(zip(["renewables","emissionsMt","netExportGdp"],en)),
     "politics":dict(zip(["democracy","corruption","approval"],pol)),
    }

if __name__=="__main__":
    out=pathlib.Path(__file__).resolve().parents[2]/"data"/"countries.json"
    out.write_text(json.dumps([rec(r) for r in R],indent=1)+"\n")
    print(f"wrote {len(R)} countries -> {out}")
